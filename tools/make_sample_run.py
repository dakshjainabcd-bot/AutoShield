"""Write web/assets/sample_run.jsonl: a 190 s REPLAY SAMPLE for the dashboard (roadmap 3.5).

IMPORTANT: this is a stand-in generated by a small script that follows the Phase 1
scenario timeline (flood 60 s, hang 90 s, drift 120 s, faulty firmware 150 s, test
burst 170 s). It is not simulator output and its 'ml' values are placeholders until
the Phase 2 SVM exists. Replace it with a real export later. The dashboard shows a
REPLAY badge while playing it, so it is never mistaken for live data.
Run from the repository root:  python tools/make_sample_run.py
"""
import json
import random
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "web" / "assets" / "sample_run.jsonl"
KINDS = {"fault_detected", "severity_change", "action_taken", "verify_ok", "verify_failed", "escalate",
         "node_isolated", "node_restored", "test_burst_started", "test_burst_ended", "sensor_flagged",
         "fw_deploy_started", "canary_started", "fw_commit", "fw_rollback", "mode_change"}
SEV = ["NORMAL", "LOW", "MEDIUM", "HIGH", "CRITICAL"]
rnd = random.Random(7)

def ev(t, kind, sev, detail):
    return {"type": "event", "v": 1, "t_ms": int(round(t * 1000)), "run_id": 1, "kind": kind,
            "node": 1, "severity": sev, "detail": detail}

# scripted events (time, kind, severity, detail) taken from the Phase 1 timeline
SCRIPT = [
    (60.3, "fault_detected", "HIGH", "flood"), (60.3, "action_taken", "HIGH", "isolate"),
    (60.3, "node_isolated", "HIGH", "relay"), (62.2, "verify_ok", "HIGH", "isolate"),
    (72.2, "node_restored", "NORMAL", "relay on, hard reset"),
    (90.2, "fault_detected", "MEDIUM", "heartbeat_missed"), (90.2, "action_taken", "MEDIUM", "soft_reset"),
    (91.2, "action_taken", "MEDIUM", "hard_reset"), (92.8, "verify_ok", "MEDIUM", "restart"),
    (150.0, "fw_deploy_started", "NORMAL", "canary"), (150.5, "canary_started", "NORMAL", "window open"),
    (153.8, "fault_detected", "CRITICAL", "canary_unhealthy"), (153.8, "action_taken", "CRITICAL", "fw_rollback"),
    (153.8, "fw_rollback", "CRITICAL", "FW_ROLLBACK sent"), (155.5, "verify_ok", "CRITICAL", "fw_rollback"),
    (170.0, "test_burst_started", "NORMAL", "2 s"), (172.0, "test_burst_ended", "NORMAL", ""),
]
ACTIONS = {(60.3): "isolate", (90.2): "soft_reset", (91.2): "hard_reset", (153.8): "fw_rollback"}

def between(t, a, b):
    return a <= t < b

def silent(t):  # node sends nothing
    return between(t, 60.3, 72.7) or between(t, 90.0, 91.7) or between(t, 150.0, 150.5) or between(t, 153.8, 154.4)

ewma, n_warn, n_fault, dstate, dflag = 0.0, 0, 0, "ok", False
lines = ["# AutoShield REPLAY SAMPLE (script generated stand-in, not simulator output; ml values are placeholders)"]
events = sorted(SCRIPT, key=lambda e: e[0])   # stable: keeps the scripted order at equal times
last_sev, ei, last_hb = "NORMAL", 0, 0.0
for k in range(1, 1901):
    t = round(k * 0.1, 1)
    while ei < len(events) and events[ei][0] <= t + 1e-9:
        lines.append(json.dumps(ev(*events[ei]))); ei += 1
    resid = 50.0 * (t - 120.0) if between(t, 120, 140) else 0.0
    ewma = 0.9 * ewma + 0.1 * (resid + rnd.gauss(0, 4))
    mag = abs(ewma)
    n_warn = n_warn + 1 if mag > 10 else 0
    n_fault = n_fault + 1 if mag > 20 else 0
    dstate = "fault" if n_fault >= 5 else "warn" if n_warn >= 5 else "ok"
    trust = round(max(0.0, min(1.0, 1 - mag / 20)), 2)
    sev = "NORMAL"
    if between(t, 60.3, 62.2): sev = "HIGH"
    elif between(t, 90.2, 92.8): sev = "MEDIUM"
    elif between(t, 153.8, 155.5): sev = "CRITICAL"
    elif not (between(t, 60, 73) or between(t, 150, 156)):
        sev = "MEDIUM" if dstate == "fault" else "LOW" if dstate == "warn" else "NORMAL"
    if dstate == "fault" and not dflag and sev != "NORMAL":
        dflag = True; lines.append(json.dumps(ev(t, "fault_detected", sev, "sensor_drift_fault")))
        lines.append(json.dumps(ev(t, "sensor_flagged", sev, "trust=0")))
    if dstate == "ok": dflag = False
    if sev != last_sev:
        if not any(abs(e[0] - t) < 0.05 for e in SCRIPT) or sev == "NORMAL":
            lines.append(json.dumps(ev(t, "severity_change", sev, f"{last_sev}->{sev}")))
        last_sev = sev
    flood = between(t, 60.0, 60.3)
    fps = 10.0 if silent(t) else 71.0
    if flood: fps += 1500
    if between(t, 153.5, 153.8) or between(t, 152.0, 153.8) and int(t * 10) % 10 == 0: fps += 30
    if between(t, 170, 172): fps += 500
    fps = round(max(0.0, fps + rnd.gauss(0, 1.2)), 1)
    if not silent(t):
        last_hb = t - (t * 1000 % 100) / 1000.0
    hb_age = int(round((t - last_hb) * 1000))
    canary = between(t, 150.5, 153.8)
    state = "MISSING" if hb_age > 300 else "CANARY" if canary else "RUN"
    bad = between(t, 60.0, 62.2) or between(t, 90.0, 92.8) or between(t, 152.0, 155.5)
    score = round((1.21 if bad else -0.5) + rnd.gauss(0, 0.03), 2)
    act = next((v for key, v in ACTIONS.items() if abs(key - t) < 0.05), None)
    gz = int(500 * __import__("math").sin(6.283 * t / 20) + (50 * (t - 120) if between(t, 120, 140) else 0))
    msg = {"type": "telemetry", "v": 1, "mode": "sim", "t_ms": int(t * 1000), "run_id": 1,
           "bus": {"fps": fps, "load_pct": round(fps * 111 / 5000, 1), "rx_overflow": 0},
           "features": [fps, 0.7 if not flood else 0.95, 1000.0 if silent(t) else 100.0, 0.6, 1000.0 if silent(t) else 20.0, 0.4],
           "ml": {"anomaly_score": score, "threshold": 0.0, "anomaly": score > 0, "model": "sample"},
           "monitors": {"hb_age_ms": hb_age, "flood": flood, "drift_ewma": round(ewma, 1), "drift_state": dstate},
           "nodes": [{"id": 1, "state": state, "bank": "B" if canary else "A", "fw": "1.1.1" if canary else "1.0.0",
                      "ota_state": "PENDING_VERIFY" if canary else "VALID", "isolated": between(t, 60.3, 72.2)}],
           "sensor": {"node": 1, "gz_cdps": gz, "ref_gz_cdps": gz - int(resid), "trust": trust},
           "context": {"test_burst": between(t, 170, 173), "auto_recovery": True},
           "severity": sev, "action": act}
    lines.append(json.dumps(msg))

# validate against the contract before writing
tele = ev_n = 0
for ln in lines[1:]:
    m = json.loads(ln)
    if m["type"] == "telemetry":
        assert set(m) == {"type", "v", "mode", "t_ms", "run_id", "bus", "features", "ml", "monitors", "nodes",
                          "sensor", "context", "severity", "action"} and len(m["features"]) == 6 and m["severity"] in SEV
        tele += 1
    else:
        assert m["kind"] in KINDS and m["severity"] in SEV and len(m) == 8
        ev_n += 1
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {OUT.name}: {tele} telemetry lines, {ev_n} events, all valid against the contract.")
